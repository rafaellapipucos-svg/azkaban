/**
 * After `expo export`: adds the full CSP to `dist/_headers` as `Content-Security-Policy-Report-Only`,
 * with the exact Supabase host of this build (ADR-0008, section 17; ADR-0012, section 13, item 1). No
 * wildcard: `*.supabase.co` would let the page talk to anyone's project. It becomes the enforced
 * policy only after a clean run on the hosted app. The minimal enforced CSP in `public/_headers` stays
 * as it is.
 *
 * Then writes `dist/.htaccess` for the Hostinger (Apache/LiteSpeed, BL-24), which ignores `_headers`
 * and `_redirects`: the same `/*` headers, the SPA fallback, HTTPS and the cache rules.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const enforcedLine =
  "  Content-Security-Policy: frame-ancestors 'none'; object-src 'none'; base-uri 'self'";

export function reportOnlyCsp(supabaseUrl: string): string {
  const { origin, protocol } = new URL(supabaseUrl);
  if (protocol !== 'https:' && protocol !== 'http:') {
    throw new Error(`EXPO_PUBLIC_SUPABASE_URL must be http or https, got ${protocol}`);
  }
  const realtime = origin.replace(/^http/, 'ws');
  return [
    "default-src 'self'",
    "script-src 'self'",
    // react-native-web writes styles at run time, and index.html has a <style>.
    "style-src 'self' 'unsafe-inline'",
    `img-src 'self' data: blob: ${origin}`,
    `connect-src 'self' ${origin} ${realtime}`,
    "font-src 'self' data:",
    "worker-src 'self'",
    "manifest-src 'self'",
    "frame-ancestors 'none'",
    "object-src 'none'",
    "base-uri 'self'",
  ].join('; ');
}

export function withReportOnlyCsp(headers: string, supabaseUrl: string): string {
  const lines = headers.split(/\r?\n/);
  const at = lines.indexOf(enforcedLine);
  if (at === -1) throw new Error('public/_headers lost its Content-Security-Policy line');
  lines.splice(at + 1, 0, `  Content-Security-Policy-Report-Only: ${reportOnlyCsp(supabaseUrl)}`);
  return lines.join('\n');
}

/** The `/*` block of a `_headers` file as `[name, value]` pairs. */
function allRoutesHeaders(headers: string): [string, string][] {
  const block = headers
    .replace(/\r/g, '')
    .split(/\n(?=\S)/)
    .find((each) => each.startsWith('/*\n'));
  if (!block) throw new Error('_headers has no /* block');
  return block
    .split('\n')
    .slice(1)
    .filter((line) => line.trim())
    .map((line) => {
      const at = line.indexOf(':');
      const [name, value] = [line.slice(0, at).trim(), line.slice(at + 1).trim()];
      if (at === -1 || !/^[A-Za-z-]+$/.test(name) || /["\\]/.test(value)) {
        throw new Error(`_headers line cannot go to .htaccess: ${line}`);
      }
      return [name, value];
    });
}

/**
 * `.htaccess` for the web root, from the built `_headers`, so both hosts send the same headers.
 * Hashed names (`-<md5>.js` in `_expo/static`, `.<md5>.ttf` in `assets`) are cached for a year; the
 * document, the service worker and the manifest are revalidated on every load.
 */
export function htaccess(headers: string): string {
  const security = allRoutesHeaders(headers).map(
    ([name, value]) => `  Header always set ${name} "${value}"`,
  );
  return [
    '# Generated by apps/app/scripts/headers.ts on `pnpm build:web`. Edit the script, not this file.',
    'Options -Indexes',
    'DirectoryIndex index.html',
    'AddType application/manifest+json .webmanifest',
    'AddType text/javascript .js',
    '',
    '<IfModule mod_rewrite.c>',
    '  RewriteEngine On',
    '  RewriteCond %{HTTPS} off',
    '  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]',
    // A missing chunk or asset is a 404, not index.html served as JavaScript.
    '  RewriteCond %{REQUEST_URI} !^/(_expo|assets)/',
    '  RewriteCond %{REQUEST_FILENAME} !-f',
    '  RewriteRule ^ index.html [L]',
    '</IfModule>',
    '',
    '<IfModule mod_headers.c>',
    ...security,
    '  <FilesMatch "[.-][0-9a-f]{32}\\.[a-z0-9]+$">',
    '    Header set Cache-Control "public, max-age=31536000, immutable"',
    '  </FilesMatch>',
    '  <FilesMatch "^(index\\.html|sw\\.js|manifest\\.webmanifest)$">',
    '    Header set Cache-Control "no-cache"',
    '  </FilesMatch>',
    '</IfModule>',
    '',
    // The upload action keeps its sync state in the web root; nothing in it is secret, but it is no page.
    '<Files ".ftp-deploy-sync-state.json">',
    '  Require all denied',
    '</Files>',
    '',
  ].join('\n');
}

// Node 24 sets `main` when this file is the one being run; a test that imports it gets undefined.
if ((import.meta as { main?: boolean }).main) {
  const file = new URL('../dist/_headers', import.meta.url);
  const url = process.env.EXPO_PUBLIC_SUPABASE_URL;
  if (!url) {
    // ponytail: report-only enforces nothing, so a build without the URL keeps the minimal CSP.
    console.warn('EXPO_PUBLIC_SUPABASE_URL is not set: dist/_headers keeps only the minimal CSP.');
  } else {
    writeFileSync(file, withReportOnlyCsp(readFileSync(file, 'utf8'), url));
  }
  writeFileSync(
    new URL('../dist/.htaccess', import.meta.url),
    htaccess(readFileSync(file, 'utf8')),
  );
}
